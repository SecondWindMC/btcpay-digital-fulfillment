#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const config = JSON.parse(fs.readFileSync(path.join(root, 'products.config.json'), 'utf8'));
const outDir = path.join(root, 'netlify', 'functions', 'data');
fs.mkdirSync(outDir, { recursive: true });

const entries = Object.entries(config).map(([itemCode, product]) => {
  const zipPath = path.join(root, 'products', product.zip);
  if (!fs.existsSync(zipPath)) throw new Error(`Missing zip for ${itemCode}: ${zipPath}`);
  return {
    itemCode,
    name: product.name,
    filename: product.filename,
    data: fs.readFileSync(zipPath).toString('base64'),
  };
});

const output = `// Generated by scripts/build-product-data.js. Do not edit by hand.\nmodule.exports = ${JSON.stringify(entries, null, 2)};\n`;
fs.writeFileSync(path.join(outDir, 'products.js'), output);
console.log(`generated ${entries.length} product data entries`);
